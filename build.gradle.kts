import net.ltgt.gradle.errorprone.CheckSeverity
import net.ltgt.gradle.errorprone.errorprone

plugins {
  `java-library`
  jacoco
  alias(libs.plugins.errorprone)
  alias(libs.plugins.spotless)
  alias(libs.plugins.maven.publish)
}

description = "The official Didit Java and Kotlin library for the Didit API."

// The compiler runs on JDK 21 (errorprone needs it) and emits Java 11 bytecode. Tests run on the
// JDK given by -PtestJavaVersion (CI runs 11, 17, 21 and 25).
val compileJdk = 21
val testJdk = providers.gradleProperty("testJavaVersion").map(String::toInt).orElse(compileJdk)

java { toolchain { languageVersion = JavaLanguageVersion.of(compileJdk) } }

dependencies {
  api(libs.jackson.databind)
  api(libs.jspecify)

  errorprone(libs.errorprone.core)
  errorprone(libs.nullaway)

  testImplementation(platform(libs.junit.bom))
  testImplementation(libs.junit.jupiter)
  testRuntimeOnly(libs.junit.launcher)
}

val generatedSources =
  listOf("me/didit/resources/**", "me/didit/types/**")

tasks.withType<JavaCompile>().configureEach {
  options.release = 11
  options.encoding = "UTF-8"
  options.isFork = true
  options.forkOptions.memoryMaximumSize = "3g"
  options.compilerArgs.addAll(listOf("-Xlint:all", "-Xlint:-processing", "-Werror", "-parameters"))
  options.errorprone {
    check("NullAway", CheckSeverity.ERROR)
    option("NullAway:OnlyNullMarked", "true")
    option("NullAway:JSpecifyMode", "true")
    // Generated files repeat simple names such as Builder in nested classes on purpose.
    disable("SameNameButDifferent")
    // Generated builders and union accessors are intentionally symmetric.
    disable("InlineMeSuggester")
  }
}

tasks.named<JavaCompile>("compileTestJava") {
  options.errorprone {
    // Tests stub nullable values and use reflection over the generated API.
    disable("NullAway")
    // Style checks that only add noise to test code.
    disable("StringSplitter", "CanonicalDuration", "InputStreamSlowMultibyteRead")
  }
}

tasks.withType<Javadoc>().configureEach {
  (options as StandardJavadocDocletOptions).apply {
    encoding = "UTF-8"
    addStringOption("Xdoclint:all,-missing", "-quiet")
    addBooleanOption("Xwerror", true)
    links("https://docs.oracle.com/en/java/javase/11/docs/api/")
  }
  isFailOnError = true
  maxMemory = "2g"
}

tasks.test {
  useJUnitPlatform { excludeTags("live") }
  javaLauncher = javaToolchains.launcherFor { languageVersion = testJdk.map(JavaLanguageVersion::of) }
  maxHeapSize = "1g"
  systemProperty("didit.repoRoot", rootDir.absolutePath)
  testLogging {
    events("failed", "skipped")
    exceptionFormat = org.gradle.api.tasks.testing.logging.TestExceptionFormat.FULL
  }
  finalizedBy(tasks.jacocoTestReport)
}

// Opt-in smoke tests against a sandbox application; they skip themselves without
// DIDIT_SANDBOX_API_KEY.
val liveTest by
  tasks.registering(Test::class) {
    description = "Runs the live sandbox smoke tests (needs DIDIT_SANDBOX_API_KEY)."
    group = "verification"
    testClassesDirs = sourceSets.test.get().output.classesDirs
    classpath = sourceSets.test.get().runtimeClasspath
    useJUnitPlatform { includeTags("live") }
    systemProperty("didit.repoRoot", rootDir.absolutePath)
  }

// Coverage gate for the hand-written core (DESIGN 11): 90 % of lines.
val coreClasses =
  sourceSets.main.map { main ->
    main.output.classesDirs.asFileTree.matching {
      include("me/didit/*.class", "me/didit/core/**", "me/didit/errors/**", "me/didit/webhooks/**", "me/didit/authentication/**")
    }
  }

tasks.jacocoTestReport {
  dependsOn(tasks.test)
  classDirectories.setFrom(coreClasses)
  reports {
    xml.required = true
    html.required = true
  }
}

tasks.jacocoTestCoverageVerification {
  dependsOn(tasks.test)
  classDirectories.setFrom(coreClasses)
  violationRules { rule { limit { counter = "LINE"; minimum = "0.90".toBigDecimal() } } }
}

tasks.check { dependsOn(tasks.jacocoTestCoverageVerification) }

// The generated layer is checked by regenerating it (codegen/generate.py --check), not formatted.
spotless {
  java {
    target("src/**/*.java")
    targetExclude(
      "src/main/java/me/didit/resources/**",
      "src/main/java/me/didit/types/**",
      "src/test/java/me/didit/resources/**",
    )
    googleJavaFormat(libs.versions.google.java.format.get())
  }
  kotlinGradle {
    target("*.gradle.kts", "examples/*.gradle.kts")
    ktfmt().googleStyle()
  }
}

