HEADER = "// Code generated by codegen from openapi/*.json. DO NOT EDIT.\n"
TYPES_PKG = "me.didit.types"
RESOURCES_PKG = "me.didit.resources"
CORE_PKG = "me.didit.core"

# Hand-written core classes a generated resource extends (DESIGN 9: the webhook
# verifier lives in the core and is reachable as client.webhooks().verify(...)).
RESOURCE_BASES = {"webhooks": "me.didit.webhooks.WebhookMethods"}

DETECT_JSON_TYPE = {
    "string": "json.isTextual()",
    "integer": "json.isIntegralNumber()",
    "number": "json.isNumber()",
    "boolean": "json.isBoolean()",
    "array": "json.isArray()",
    "any": "!json.isNull()",
}


@dataclass
class Ctx:
    """Emission context of one Java file: package, top-level class and imports."""

    package: str
    top: JClass | None
    imports: set[str] = field(default_factory=set)

    def use(self, qualified: str) -> str:
        self.imports.add(qualified)
        return qualified.rsplit(".", 1)[1]

    def ref(self, cls: JClass) -> str:
        if self.top is not None and cls.top is self.top:
            return cls.qualified
        top = cls.top
        shadowed = self.top is not None and top.name in self.top.nested_names()
        if shadowed:
            return f"{TYPES_PKG}.{cls.qualified}"
        if self.package != TYPES_PKG:
            self.imports.add(f"{TYPES_PKG}.{top.name}")
        return cls.qualified

    def java_type(self, t: TypeRef, boxed: bool = True) -> str:
        k = t.kind
        if k == "string":
            return "String"
        if k == "long":
            return "Long" if boxed else "long"
        if k == "double":
            return "Double" if boxed else "double"
        if k == "boolean":
            return "Boolean" if boxed else "boolean"
        if k == "datetime":
            return self.use("java.time.OffsetDateTime")
        if k == "date":
            return self.use("java.time.LocalDate")
        if k == "any":
            return self.use("com.fasterxml.jackson.databind.JsonNode")
        if k == "object":
            self.use("java.util.Map")
            return f"Map<String, {self.use('com.fasterxml.jackson.databind.JsonNode')}>"
        if k == "file":
            return self.use("me.didit.core.FileUpload")
        if k == "list":
            assert t.item is not None
            self.use("java.util.List")
            return f"List<{self.java_type(t.item)}>"
        if k == "map":
            assert t.item is not None
            self.use("java.util.Map")
            return f"Map<String, {self.java_type(t.item)}>"
        if k == "class":
            assert t.cls is not None
            return self.ref(t.cls)
        raise ValueError(f"unknown type kind {k}")

    def conv(self, t: TypeRef) -> str:
        self.use("me.didit.core.Conv")
        k = t.kind
        simple = {
            "string": "Conv.STRING",
            "long": "Conv.LONG",
            "double": "Conv.DOUBLE",
            "boolean": "Conv.BOOLEAN",
            "datetime": "Conv.DATE_TIME",
            "date": "Conv.DATE",
            "any": "Conv.ANY",
            "object": "Conv.OBJECT",
        }
        if k in simple:
            return simple[k]
        if k == "list":
            assert t.item is not None
            return f"Conv.list({self.conv(t.item)})"
        if k == "map":
            assert t.item is not None
            return f"Conv.map({self.conv(t.item)})"
        if k == "class":
            assert t.cls is not None
            ref = self.ref(t.cls)
            if t.cls.kind == "enum":
                return f"Conv.enumeration({ref}::of)"
            if t.cls.kind == "union":
                return f"Conv.union({ref}::fromJson)"
            return f"Conv.model({ref}::fromJson)"
        raise ValueError(f"no converter for {k}")


def imports_block(ctx: Ctx, own_package: str) -> str:
    lines = sorted(
        imp for imp in ctx.imports if imp.rsplit(".", 1)[0] != own_package and not imp.startswith("java.lang.")
    )
    if not lines:
        return ""
    return "".join(f"import {imp};\n" for imp in lines) + "\n"


def file_text(ctx: Ctx, body: str) -> str:
    return f"{HEADER}package {ctx.package};\n\n{imports_block(ctx, ctx.package)}{body}"


def deprecated_lines(text: str = "") -> list[str]:
    return ["", "@deprecated " + (javadoc.escape(text) if text else "Deprecated by the API.")]


