def emit_class(cls: JClass, ctx: Ctx, indent: str) -> str:
    if cls.kind == "model":
        return emit_model(cls, ctx, indent)
    if cls.kind == "enum":
        return emit_enum(cls, ctx, indent)
    if cls.kind == "union":
        return emit_union(cls, ctx, indent)
    if cls.kind == "status":
        return emit_status(cls, ctx, indent)
    raise ValueError(cls.kind)


def class_doc(cls: JClass, indent: str) -> str:
    lines = javadoc.render(cls.description)
    if cls.deprecated:
        lines += deprecated_lines()
    return javadoc.block(lines, indent)


def modifiers(cls: JClass) -> str:
    return "public final class" if cls.outer is None else "public static final class"


def emit_model(cls: JClass, ctx: Ctx, indent: str) -> str:
    i1 = indent + "  "
    i2 = indent + "    "
    ref = ctx.ref(cls)
    ctx.use("me.didit.core.JsonModel")
    ctx.use("me.didit.core.Json")
    ctx.use("java.util.Set")
    ctx.use("java.util.List")
    ctx.use("java.util.Map")
    ctx.use("com.fasterxml.jackson.databind.JsonNode")
    ctx.use("com.fasterxml.jackson.databind.node.ObjectNode")
    ctx.use("me.didit.core.FileUpload")
    out: list[str] = []
    out.append(class_doc(cls, indent))
    if cls.deprecated:
        out.append(f"{indent}@Deprecated\n")
    out.append(f"{indent}{modifiers(cls)} {cls.name} extends JsonModel {{\n")
    known = ", ".join(f'"{p.json_name}"' for p in cls.props)
    out.append(f"{i1}private static final Set<String> KNOWN_FIELDS = Set.of({known});\n\n")
    out.append(f"{i1}private {cls.name}(ObjectNode json, Map<String, List<FileUpload>> files) {{\n")
    out.append(f"{i2}super(json, files);\n{i1}}}\n\n")
    out.append(
        f"{i1}/**\n{i1} * Reads a {{@code {cls.name}}} from JSON. Unknown fields are kept and readable\n"
        f"{i1} * through {{@link #_additionalProperties()}}.\n{i1} *\n"
        f"{i1} * @param json a JSON object\n{i1} * @return the parsed value\n{i1} */\n"
    )
    out.append(f"{i1}public static {cls.name} fromJson(JsonNode json) {{\n")
    out.append(f"{i2}return new {cls.name}(Json.copyObject(json), Map.of());\n{i1}}}\n\n")
    out.append(f"{i1}/**\n{i1} * Returns an empty builder.\n{i1} *\n{i1} * @return a new builder\n{i1} */\n")
    out.append(f"{i1}public static Builder builder() {{\n{i2}return new Builder();\n{i1}}}\n\n")
    out.append(
        f"{i1}/**\n{i1} * Returns a builder holding a copy of every field of this value.\n{i1} *\n"
        f"{i1} * @return a new builder\n{i1} */\n"
    )
    out.append(f"{i1}public Builder toBuilder() {{\n{i2}return new Builder(this);\n{i1}}}\n")
    for prop in cls.props:
        out.append("\n")
        out.append(emit_getter(prop, ctx, i1))
    out.append(f"\n{i1}@Override\n{i1}protected Set<String> knownFields() {{\n{i2}return KNOWN_FIELDS;\n{i1}}}\n")
    # Builder
    out.append(f"\n{i1}/** Builds a {{@link {cls.name}}}. */\n")
    out.append(f"{i1}public static final class Builder extends JsonModel.BaseBuilder<Builder> {{\n")
    out.append(f"{i2}private Builder() {{}}\n\n")
    out.append(f"{i2}private Builder({cls.name} from) {{\n{i2}  super(from);\n{i2}}}\n")
    for prop in cls.props:
        out.append("\n")
        out.append(emit_setter(prop, ctx, i2))
    required = [p for p in cls.props if p.required]
    out.append(
        f"\n{i2}/**\n{i2} * Builds the value.\n{i2} *\n{i2} * @return a new immutable {{@code {cls.name}}}\n"
    )
    if required:
        out.append(f"{i2} * @throws IllegalStateException when a required field is missing\n")
    out.append(f"{i2} */\n{i2}public {cls.name} build() {{\n")
    for prop in required:
        if prop.type.kind == "file" or (prop.type.kind == "list" and prop.type.item and prop.type.item.kind == "file"):
            out.append(f'{i2}  requireFile("{prop.json_name}");\n')
        else:
            out.append(f'{i2}  require("{prop.json_name}", {"true" if prop.nullable else "false"});\n')
    out.append(f"{i2}  return new {cls.name}(buildJson(), buildFiles());\n{i2}}}\n")
    out.append(f"\n{i2}@Override\n{i2}protected Builder self() {{\n{i2}  return this;\n{i2}}}\n")
    out.append(f"{i1}}}\n")
    for nested in cls.nested:
        out.append("\n")
        out.append(emit_class(nested, ctx, i1))
    out.append(f"{indent}}}\n")
    _ = ref
    return "".join(out)


def prop_doc(prop: Prop, extra: list[str], indent: str) -> str:
    lines = javadoc.render(prop.description)
    if not lines:
        lines = [f"The <code>{javadoc.escape(prop.json_name)}</code> field."]
    lines += extra
    if prop.deprecated:
        lines += deprecated_lines()
    return javadoc.block(lines, indent)


def is_file(t: TypeRef) -> bool:
    return t.kind == "file" or (t.kind == "list" and t.item is not None and t.item.kind == "file")


def emit_getter(prop: Prop, ctx: Ctx, indent: str) -> str:
    out: list[str] = []
    required = prop.required and not prop.nullable
    if is_file(prop.type):
        jt = ctx.java_type(prop.type)
        ctx.use("java.util.Optional")
        returns = f"Optional<{jt}>"
        accessor = "file" if prop.type.kind == "file" else "fileList"
        body = f'return {accessor}("{prop.json_name}");'
        extra = ["", "@return the file to upload, if set"]
    elif required:
        returns = ctx.java_type(prop.type, boxed=False)
        body = f'return Json.required(json, "{prop.json_name}", {ctx.conv(prop.type)});'
        extra = ["", "@return the value", "@throws me.didit.errors.UnexpectedResponseException when the field is absent or has another type"]
    else:
        ctx.use("java.util.Optional")
        returns = f"Optional<{ctx.java_type(prop.type)}>"
        body = f'return Json.optional(json, "{prop.json_name}", {ctx.conv(prop.type)});'
        extra = ["", "@return the value, or empty when the field is absent or null",
                 "@throws me.didit.errors.UnexpectedResponseException when the field has another type"]
    out.append(prop_doc(prop, extra, indent))
    if prop.deprecated:
        out.append(f"{indent}@Deprecated\n")
    out.append(f"{indent}public {returns} {prop.java_name}() {{\n{indent}  {body}\n{indent}}}\n")
    return "".join(out)


def emit_setter(prop: Prop, ctx: Ctx, indent: str) -> str:
    out: list[str] = []
    name = prop.java_name
    param = names.safe_param(name)
    nullable = prop.nullable and not is_file(prop.type)
    if is_file(prop.type):
        jt = ctx.java_type(prop.type)
        call = "setFile" if prop.type.kind == "file" else "setFiles"
        decl = f"{jt} {param}"
        body = f'return {call}("{prop.json_name}", {param});'
    elif prop.type.kind in ("any",):
        ctx.use("org.jspecify.annotations.Nullable")
        decl = f"@Nullable Object {param}"
        body = f'return setAny("{prop.json_name}", {param});'
    elif prop.type.kind == "object":
        ctx.use("java.util.Map")
        if nullable:
            ctx.use("org.jspecify.annotations.Nullable")
            decl = f"@Nullable Map<String, ?> {param}"
        else:
            decl = f"Map<String, ?> {param}"
        body = f'return setAny("{prop.json_name}", {param});'
    else:
        jt = ctx.java_type(prop.type, boxed=nullable)
        if nullable:
            ctx.use("org.jspecify.annotations.Nullable")
            decl = f"{nullable_type(jt)} {param}"
            body = f'return setNullable("{prop.json_name}", {ctx.conv(prop.type)}, {param});'
        else:
            decl = f"{jt} {param}"
            body = f'return set("{prop.json_name}", {ctx.conv(prop.type)}, {param});'
    extra = ["", f"@param {param} the value" + (", or {@code null} to send JSON null" if nullable else ""),
             "@return this builder"]
    out.append(prop_doc(prop, extra, indent))
    if prop.deprecated:
        out.append(f"{indent}@Deprecated\n")
    out.append(f"{indent}public Builder {name}({decl}) {{\n{indent}  {body}\n{indent}}}\n")
    if prop.type.kind == "file":
        ctx.use("me.didit.core.FileUpload")
        out.append(
            f"\n{indent}/**\n{indent} * Uploads the file at {{@code path}} as {{@code {prop.json_name}}}.\n{indent} *\n"
            f"{indent} * @param path the file to read when the request is sent\n{indent} * @return this builder\n{indent} */\n"
        )
        if prop.deprecated:
            out.append(f"{indent}@Deprecated\n")
        path = ctx.use("java.nio.file.Path")
        out.append(
            f"{indent}public Builder {name}({path} path) {{\n{indent}  return setFile(\"{prop.json_name}\", FileUpload.of(path));\n{indent}}}\n"
        )
    return "".join(out)


def emit_enum(cls: JClass, ctx: Ctx, indent: str) -> str:
    i1 = indent + "  "
    i2 = indent + "    "
    ctx.use("me.didit.core.StringEnum")
    ctx.use("java.util.List")
    out: list[str] = []
    doc = javadoc.render(cls.description) + [
        "",
        "<p>An open enum: {@link #of(String)} accepts values this SDK version does not know yet.",
    ]
    out.append(javadoc.block(doc, indent))
    out.append(f"{indent}{modifiers(cls)} {cls.name} extends StringEnum {{\n")
    used: set[str] = {"KNOWN_VALUES"}
    consts: list[str] = []
    for value in cls.values:
        const = names.constant(value)
        base = const
        n = 2
        while const in used:
            const = f"{base}_{n}"
            n += 1
        used.add(const)
        consts.append(const)
        literal = java_string(value)
        out.append(f"{i1}/** The value {{@code {javadoc.escape(literal)}}}. */\n")
        out.append(f"{i1}public static final {cls.name} {const} = new {cls.name}({literal});\n\n")
    out.append(f"{i1}private static final List<{cls.name}> KNOWN_VALUES = List.of({', '.join(consts)});\n\n")
    out.append(f"{i1}private {cls.name}(String value) {{\n{i2}super(value);\n{i1}}}\n\n")
    out.append(
        f"{i1}/**\n{i1} * Returns the constant for a known value, or a new instance for any other value.\n{i1} *\n"
        f"{i1} * @param value the string value\n{i1} * @return the enum value\n{i1} */\n"
    )
    out.append(f"{i1}public static {cls.name} of(String value) {{\n")
    out.append(f"{i2}return StringEnum.lookup(KNOWN_VALUES, value, {cls.name}::new);\n{i1}}}\n\n")
    out.append(f"{i1}/**\n{i1} * Returns the values known to this SDK version.\n{i1} *\n{i1} * @return the known values\n{i1} */\n")
    out.append(f"{i1}public static List<{cls.name}> knownValues() {{\n{i2}return KNOWN_VALUES;\n{i1}}}\n\n")
    out.append(f"{i1}@Override\n{i1}public boolean isKnown() {{\n{i2}return KNOWN_VALUES.contains(this);\n{i1}}}\n")
    out.append(f"{indent}}}\n")
    return "".join(out)


def java_string(value: str) -> str:
    out = ['"']
    for ch in value:
        code = ord(ch)
        if ch == '"':
            out.append('\\"')
        elif ch == "\\":
            out.append("\\\\")
        elif ch == "\n":
            out.append("\\n")
        elif ch == "\r":
            out.append("\\r")
        elif ch == "\t":
            out.append("\\t")
        elif code < 0x20 or code > 0x7E:
            if code > 0xFFFF:
                code -= 0x10000
                out.append(f"\\u{0xD800 + (code >> 10):04x}\\u{0xDC00 + (code & 0x3FF):04x}")
            else:
                out.append(f"\\u{code:04x}")
        else:
            out.append(ch)
    out.append('"')
    return "".join(out)


def detect_expr(variant: Variant) -> str:
    kind = variant.detect[0]
    if kind == "discriminator":
        return f'Json.hasValue(json, {java_string(variant.detect[1])}, {java_string(str(variant.detect[2]))})'
    if kind == "shape":
        required, unique = variant.detect[1], variant.detect[2]
        if required:
            return "Json.hasFields(json, " + ", ".join(java_string(r) for r in required) + ")"
        if unique:
            return "Json.hasAnyField(json, " + ", ".join(java_string(r) for r in unique) + ")"
        return "json.isObject()"
    if kind == "json_type":
        return DETECT_JSON_TYPE[variant.detect[1]]
    if kind == "status":
        return f"statusCode() == {variant.detect[1]}"
    raise ValueError(kind)


def variant_type_text(variant: Variant, ctx: Ctx) -> str:
    return ctx.java_type(variant.type)


def emit_union(cls: JClass, ctx: Ctx, indent: str) -> str:
    i1 = indent + "  "
    i2 = indent + "    "
    ctx.use("me.didit.core.JsonUnion")
    ctx.use("me.didit.core.Json")
    ctx.use("java.util.Optional")
    ctx.use("com.fasterxml.jackson.databind.JsonNode")
    out: list[str] = []
    doc = javadoc.render(cls.description) + [
        "",
        "<p>One of: " + ", ".join(f"{{@code {v.name}}}" for v in cls.variants) + ". Check with the {@code is...}",
        "methods and read with the {@code as...} methods"
        + ("; the fields every variant has are readable directly." if cls.props else "."),
    ]
    out.append(javadoc.block(doc, indent))
    out.append(f"{indent}{modifiers(cls)} {cls.name} extends JsonUnion {{\n")
    out.append(f"{i1}private {cls.name}(JsonNode json) {{\n{i2}super(json);\n{i1}}}\n\n")
    out.append(
        f"{i1}/**\n{i1} * Reads a {{@code {cls.name}}} from JSON.\n{i1} *\n{i1} * @param json any JSON value\n"
        f"{i1} * @return the union\n{i1} */\n"
    )
    out.append(f"{i1}public static {cls.name} fromJson(JsonNode json) {{\n{i2}return new {cls.name}(json.deepCopy());\n{i1}}}\n")
    for prop in cls.props:
        out.append("\n")
        out.append(emit_getter(prop, ctx, i1))
    for v in cls.variants:
        jt = variant_type_text(v, ctx)
        conv = ctx.conv(v.type)
        vdesc = javadoc.render(v.description)
        out.append(f"\n{i1}/**\n{i1} * Wraps a {{@code {v.name}}} value.\n{i1} *\n")
        out.append(f"{i1} * @param value the value\n{i1} * @return the union\n{i1} */\n")
        out.append(f"{i1}public static {cls.name} of{v.name}({jt} value) {{\n")
        out.append(f"{i2}return new {cls.name}({conv}.write(value));\n{i1}}}\n\n")
        lines = [f"Whether this value is a {{@code {v.name}}}."] + ([""] + vdesc if vdesc else []) + ["", "@return true when it matches"]
        out.append(javadoc.block(lines, i1))
        out.append(f"{i1}public boolean is{v.name}() {{\n{i2}return {detect_expr(v)};\n{i1}}}\n\n")
        out.append(
            f"{i1}/**\n{i1} * Reads this value as a {{@code {v.name}}}.\n{i1} *\n"
            f"{i1} * @return the value, or empty when {{@link #is{v.name}()}} is false\n{i1} */\n"
        )
        out.append(f"{i1}public Optional<{jt}> as{v.name}() {{\n")
        out.append(f"{i2}return is{v.name}() ? Optional.of({conv}.read(json)) : Optional.empty();\n{i1}}}\n")
    for nested in cls.nested:
        out.append("\n")
        out.append(emit_class(nested, ctx, i1))
    out.append(f"{indent}}}\n")
    return "".join(out)


def emit_status(cls: JClass, ctx: Ctx, indent: str) -> str:
    i1 = indent + "  "
    i2 = indent + "    "
    ctx.use("me.didit.core.MultiStatusResponse")
    ctx.use("java.util.Optional")
    ctx.use("com.fasterxml.jackson.databind.JsonNode")
    out: list[str] = []
    out.append(javadoc.block(javadoc.render(cls.description), indent))
    out.append(f"{indent}{modifiers(cls)} {cls.name} extends MultiStatusResponse {{\n")
    out.append(f"{i1}private {cls.name}(int statusCode, JsonNode json) {{\n{i2}super(statusCode, json);\n{i1}}}\n\n")
    out.append(
        f"{i1}/**\n{i1} * Reads the response body received with {{@code statusCode}}.\n{i1} *\n"
        f"{i1} * @param statusCode the HTTP status\n{i1} * @param json the response body\n{i1} * @return the response\n{i1} */\n"
    )
    out.append(
        f"{i1}public static {cls.name} fromResponse(int statusCode, JsonNode json) {{\n"
        f"{i2}return new {cls.name}(statusCode, json.deepCopy());\n{i1}}}\n"
    )
    for v in cls.variants:
        jt = variant_type_text(v, ctx)
        conv = ctx.conv(v.type)
        out.append(
            f"\n{i1}/**\n{i1} * Whether the API answered {v.detect[1]}.\n{i1} *\n{i1} * @return true for status {v.detect[1]}\n{i1} */\n"
        )
        out.append(f"{i1}public boolean is{v.name}() {{\n{i2}return {detect_expr(v)};\n{i1}}}\n\n")
        out.append(
            f"{i1}/**\n{i1} * The body of a {v.detect[1]} response.\n{i1} *\n"
            f"{i1} * @return the body, or empty for another status\n{i1} */\n"
        )
        out.append(f"{i1}public Optional<{jt}> as{v.name}() {{\n")
        out.append(f"{i2}return is{v.name}() ? Optional.of({conv}.read(json)) : Optional.empty();\n{i1}}}\n")
    for nested in cls.nested:
        out.append("\n")
        out.append(emit_class(nested, ctx, i1))
    out.append(f"{indent}}}\n")
    return "".join(out)


def emit_type_file(cls: JClass) -> tuple[str, str]:
    ctx = Ctx(TYPES_PKG, cls)
    body = emit_class(cls, ctx, "")
    return f"{cls.name}.java", file_text(ctx, body)


def emit_types(model: Model) -> dict[str, str]:
    files = {}
    for cls in model.classes:
        name, text = emit_type_file(cls)
        files[name] = text
    files["package-info.java"] = (
        HEADER
        + "/** Request and response types of the Didit API, generated from the OpenAPI documents. */\n"
        + "@NullMarked\npackage me.didit.types;\n\nimport org.jspecify.annotations.NullMarked;\n"
    )
    return files


